"""Idioma de la interfaz: Español / English (v1.0.14, agregado
del usuario durante la construcción de la versión).

Diseño:
- El ESPAÑOL es el idioma fuente: cada cadena visible de la UI
  se escribe en español y pasa por `t()`. En español, `t()`
  devuelve la cadena tal cual (cero riesgo para lo que ya
  funcionaba); en inglés, la busca en el catálogo `_EN`, cuya
  CLAVE es la propia cadena española. Si una cadena no está en
  el catálogo, se enseña en español: nunca una clave cruda ni
  un hueco.
- La elección vive en los ajustes (`Ajustes.idioma`, «es» por
  defecto) y se aplica con `fijar_idioma()` al arrancar (desde
  ui.main) y al cambiar el selector del panel lateral, SIN
  reiniciar la app: la ventana retraduce su carcasa y recrea la
  página visible en el idioma nuevo (el túnel VPN vive en el
  motor, fuera de la UI, y no se toca).
- Las plantillas con datos (nombres de servidor, cifras) se
  escriben con marcadores {asi} y se resuelven DESPUÉS de
  traducir: t("Conectado a {host} ({pais})", host=..., pais=...)
  traduce la plantilla entera y luego la rellena.
- Fuera del catálogo, por decisión expresa del usuario: las
  notas de versión y los textos que salen de registros
  técnicos (el detalle de OpenVPN) — esos se enseñan tal cual
  los produce la herramienta.
"""
from __future__ import annotations

IDIOMAS = ("es", "en")
IDIOMA_DEFECTO = "es"

_idioma_actual = IDIOMA_DEFECTO


def fijar_idioma(codigo: str | None) -> None:
    """Fija el idioma activo («es»/«en»; cualquier otro valor
    cae al español por defecto)."""
    global _idioma_actual
    _idioma_actual = codigo if codigo in IDIOMAS else IDIOMA_DEFECTO


def idioma_actual() -> str:
    return _idioma_actual


def t(texto: str, **marcadores) -> str:
    """Traduce una cadena visible (o una plantilla) al idioma
    activo y la rellena con los marcadores dados, si los hay."""
    if _idioma_actual == "en" and texto:
        texto = _EN.get(texto, texto)
    if marcadores:
        texto = texto.format(**marcadores)
    return texto


